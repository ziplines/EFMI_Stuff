# ============================================================
# GET ACTIVE OBJECT
# ============================================================

obj = bpy.context.active_object

if obj is None:
    raise RuntimeError("No active object. Select the wall mesh first.")

if obj.type != "MESH":
    raise RuntimeError(f"Active object '{obj.name}' is not a mesh.")


# ============================================================
# GET MESH
# ============================================================

mesh = obj.data
mesh.calc_loop_triangles()

vertices = []
indices = []


# ============================================================
# EXPORT TRIANGLES
# ============================================================

for tri in mesh.loop_triangles:
    for corner, loop_idx in enumerate(tri.loops):
        vert_idx = mesh.loops[loop_idx].vertex_index

        # Export Blender world-space coordinates. The VS performs the
        # Blender -> Endfield coordinate conversion.
        co = obj.matrix_world @ mesh.vertices[vert_idx].co

        if AXIS_SWAP:
            x = co.x
            y = co.z
            z = -co.y
        else:
            x = co.x
            y = co.y
            z = co.z

        # Per-triangle barycentric-style UVs used by wall_ps.hlsl.
        if corner == 0:
            u, v = 0.0, 0.0
        elif corner == 1:
            u, v = 1.0, 0.0
        else:
            u, v = 0.0, 1.0

        vertices.append((float(x), float(y), float(z), float(u), float(v)))

        # Every triangle corner is exported as a unique vertex. Therefore
        # the number of indices is exactly the DrawIndexed IndexCount.
        indices.append(len(vertices) - 1)


# ============================================================
# COUNTS
# ============================================================

vertex_count = len(vertices)
index_count = len(indices)
triangle_count = index_count // 3

if vertex_count == 0:
    raise RuntimeError("The selected mesh contains no triangles.")

if index_count % 3 != 0:
    raise RuntimeError("Index count is not divisible by 3.")


# ============================================================
# CREATE COMPLETE MOD DIRECTORY
# ============================================================

buffers_dir = os.path.join(OUTPUT_DIR, "Buffers")
shaders_dir = os.path.join(OUTPUT_DIR, "Shaders")

os.makedirs(buffers_dir, exist_ok=True)
os.makedirs(shaders_dir, exist_ok=True)

vb_path = os.path.join(buffers_dir, "walls_vb.buf")
ib_path = os.path.join(buffers_dir, "walls_ib.buf")
mod_path = os.path.join(OUTPUT_DIR, "mod.ini")
vs_path = os.path.join(shaders_dir, "wall_vs.hlsl")
ps_path = os.path.join(shaders_dir, "wall_ps.hlsl")


# ============================================================
# WRITE BUFFERS
# ============================================================

with open(vb_path, "wb") as f:
    for vertex in vertices:
        f.write(struct.pack("<5f", *vertex))

with open(ib_path, "wb") as f:
    for index in indices:
        f.write(struct.pack("<I", index))


# ============================================================
# WRITE MOD + SHADERS
# ============================================================

with open(mod_path, "w", encoding="utf-8", newline="\n") as f:
    f.write(build_mod_ini(index_count))

with open(vs_path, "w", encoding="utf-8", newline="\n") as f:
    f.write(WALL_VS)

with open(ps_path, "w", encoding="utf-8", newline="\n") as f:
    f.write(WALL_PS)


# ============================================================
# VALIDATION
# ============================================================

actual_vb_size = os.path.getsize(vb_path)
actual_ib_size = os.path.getsize(ib_path)

expected_vb_size = vertex_count * 20
expected_ib_size = index_count * 4

if actual_vb_size != expected_vb_size:
    raise RuntimeError(
        "Vertex buffer size does not match the expected 20-byte vertex stride."
    )

if actual_ib_size != expected_ib_size:
    raise RuntimeError(
        "Index buffer size does not match the expected 4-byte index format."
    )


# ============================================================
# REPORT
# ============================================================

print()
print("========================================")
print("EFMI AIR WALL MOD EXPORT")
print("========================================")
print(f"Object:       {obj.name}")
print(f"Vertices:     {vertex_count}")
print(f"Indices:      {index_count}")
print(f"Triangles:    {triangle_count}")
print("Stride:       20 bytes")
print(f"Axis swap:    {AXIS_SWAP}")
print(f"Draw call:    drawindexed = {index_count}, 0, 0")
print("========================================")
print()
print("Generated:")
print(f"  {mod_path}")
print(f"  {vb_path}")
print(f"  {ib_path}")
print(f"  {vs_path}")
print(f"  {ps_path}")
print()
print("Export successful.")
