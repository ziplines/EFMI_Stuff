import bpy
import struct
import os


# ============================================================
# CONFIGURATION
# ============================================================

OUTPUT_DIR = r"C:\Users\RedCraft86\Desktop\Endfield\AirWalls"

# Keep False with the current shader, because wall_vs.hlsl already performs
# Blender (X,Y,Z) -> Endfield (X,Z,-Y).
AXIS_SWAP = False

# Self-depth buffer dimensions used by the current working mod.
DEPTH_WIDTH = 1920
DEPTH_HEIGHT = 1080


# ============================================================
# GENERATED SHADERS
# ============================================================

WALL_VS = r'''// Shaders/wall_vs.hlsl

cbuffer TerrainCB0 : register(b0)
{
    float4 cb0[82];
};

cbuffer TerrainCB1 : register(b1)
{
    float4 cb1[20];
};

struct VSOut
{
    float4 pos : SV_Position;
    float2 uv : TEXCOORD0;
    nointerpolation float dist : TEXCOORD1;
};

VSOut main(
    float3 inPos : POSITION,
    float2 inUV : TEXCOORD0
)
{
    VSOut o;

    float3 gamePos = float3(
         inPos.x,
         inPos.z,
        -inPos.y
    );

    float3 relativePos =
        gamePos - cb0[44].xyz;

    o.dist = length(relativePos);

    float4 clip =
          cb0[32] * relativePos.x
        + cb0[33] * relativePos.y
        + cb0[34] * relativePos.z
        + cb0[35];

    float2 jitter =
        cb1[19].zw * clip.w;

    clip.xy +=
        -jitter * float2(2.0, -2.0);

    clip.y = -clip.y;

    o.pos = clip;
    o.uv = inUV;

    return o;
}
'''

WALL_PS = r'''float4 main(
    float4 pos : SV_Position,
    float2 uv  : TEXCOORD0,
    nointerpolation float dist : TEXCOORD1
) : SV_Target
{
    const float MAX_DIST = 200.0;
    if (dist > MAX_DIST)
        discard;

    float3 bary = float3(
        uv.x,
        uv.y,
        1.0 - uv.x - uv.y
    );

    float3 derivative =
        fwidth(bary);

    const float INNER_WIDTH = 1.5;
    const float OUTER_WIDTH = 2.0;

    float3 interiorMask =
        smoothstep(
            derivative * INNER_WIDTH,
            derivative * OUTER_WIDTH,
            bary
        );

    float interior =
        min(
            interiorMask.x,
            min(
                interiorMask.y,
                interiorMask.z
            )
        );

    float edge =
        1.0 - interior;

    float4 faceColor = float4(
        0.0,
        1.0,
        1.0,
        0.1
    );

    float4 edgeColor = float4(
        0.0,
        0.1,
        0.3,
        0.5
    );

    return lerp(
        faceColor,
        edgeColor,
        edge
    );
}
'''


